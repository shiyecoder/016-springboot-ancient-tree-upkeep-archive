-- 古树名木养护档案管理系统 数据库初始化脚本
-- MySQL 8 / utf8mb4；含建库、建表、索引、字典与测试数据
-- 图片全部指向项目内真实本地文件 /uploads/seed/...，无外链、无占位图

DROP DATABASE IF EXISTS new_016;
CREATE DATABASE new_016 DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE new_016;

-- ---------------- 系统表 ----------------
CREATE TABLE sys_org (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
  org_name VARCHAR(100) NOT NULL COMMENT '组织名称',
  org_type VARCHAR(20) NOT NULL COMMENT '类型：主管单位/养护单位',
  parent_id BIGINT DEFAULT 0 COMMENT '上级组织',
  contact VARCHAR(50) COMMENT '联系人',
  phone VARCHAR(30) COMMENT '电话',
  create_time DATETIME COMMENT '创建时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='组织';
CREATE TABLE sys_role (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  role_code VARCHAR(30) NOT NULL UNIQUE COMMENT '角色编码',
  role_name VARCHAR(50) NOT NULL COMMENT '角色名称',
  description VARCHAR(200) COMMENT '说明',
  data_scope VARCHAR(10) NOT NULL DEFAULT 'SELF' COMMENT '数据范围 ALL/ORG/SELF',
  create_time DATETIME
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='角色';
CREATE TABLE sys_user (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  username VARCHAR(50) NOT NULL UNIQUE COMMENT '登录账号',
  password VARCHAR(100) NOT NULL COMMENT 'BCrypt 密码',
  real_name VARCHAR(50) NOT NULL COMMENT '姓名',
  phone VARCHAR(30) COMMENT '联系电话',
  email VARCHAR(80) COMMENT '邮箱',
  avatar VARCHAR(200) COMMENT '头像相对路径',
  role_code VARCHAR(30) NOT NULL COMMENT '角色编码',
  org_id BIGINT COMMENT '组织ID',
  org_name VARCHAR(100) COMMENT '组织名称',
  data_scope VARCHAR(10) NOT NULL DEFAULT 'SELF' COMMENT '数据范围',
  status TINYINT NOT NULL DEFAULT 1 COMMENT '1启用 0停用',
  fail_count INT DEFAULT 0 COMMENT '连续失败次数',
  lock_until DATETIME COMMENT '锁定截止时间',
  last_login_time DATETIME COMMENT '最近登录',
  create_time DATETIME
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户';
CREATE INDEX idx_user_role ON sys_user(role_code);
CREATE TABLE sys_menu (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  parent_id BIGINT DEFAULT 0 COMMENT '父菜单，0为顶级',
  menu_name VARCHAR(50) NOT NULL,
  path VARCHAR(100) COMMENT '前端路由',
  icon VARCHAR(50) COMMENT '图标',
  menu_type VARCHAR(10) NOT NULL DEFAULT '菜单' COMMENT '目录/菜单/按钮',
  sort_no INT DEFAULT 0,
  visible TINYINT DEFAULT 1,
  create_time DATETIME
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='菜单';
CREATE TABLE sys_role_menu (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  role_code VARCHAR(30) NOT NULL,
  menu_id BIGINT NOT NULL,
  UNIQUE KEY uk_role_menu (role_code, menu_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='角色菜单';
CREATE TABLE sys_dict (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  dict_type VARCHAR(50) NOT NULL COMMENT '字典类型',
  dict_label VARCHAR(50) NOT NULL COMMENT '显示名',
  dict_value VARCHAR(50) NOT NULL COMMENT '值',
  sort_no INT DEFAULT 0,
  status TINYINT DEFAULT 1,
  KEY idx_dict_type (dict_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='字典';
CREATE TABLE sys_message (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  title VARCHAR(100) NOT NULL,
  content VARCHAR(500) NOT NULL,
  msg_type VARCHAR(30) NOT NULL COMMENT '待审批/即将超时/已退回/待验收/处理完成',
  biz_no VARCHAR(50) COMMENT '业务编号',
  link_url VARCHAR(200) COMMENT '详情跳转',
  receiver_id BIGINT COMMENT '接收人',
  is_read TINYINT DEFAULT 0,
  create_time DATETIME,
  KEY idx_msg_receiver (receiver_id, is_read)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='站内消息';
CREATE TABLE sys_log (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  user_id BIGINT,
  user_name VARCHAR(50),
  action VARCHAR(100) COMMENT '动作',
  method VARCHAR(100) COMMENT '请求方法',
  params VARCHAR(500),
  ip VARCHAR(50),
  cost_ms BIGINT,
  create_time DATETIME,
  KEY idx_log_time (create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='操作日志';

-- ---------------- 业务表 ----------------
CREATE TABLE ancient_tree (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tree_code VARCHAR(50) NOT NULL COMMENT '档案编号，业务唯一',
  species VARCHAR(50) NOT NULL COMMENT '树种',
  age_estimate INT COMMENT '估测树龄（年）',
  location VARCHAR(200) NOT NULL COMMENT '所在位置',
  ownership VARCHAR(50) COMMENT '所有权',
  protect_level VARCHAR(20) NOT NULL COMMENT '保护等级',
  tree_height DECIMAL(6,2) COMMENT '树高（米）',
  diameter DECIMAL(6,2) COMMENT '胸径（厘米）',
  crown_width DECIMAL(6,2) COMMENT '冠幅（米）',
  health_level VARCHAR(10) COMMENT '健康等级',
  growth_status VARCHAR(50) COMMENT '生长状况',
  story VARCHAR(1000) COMMENT '历史故事',
  region VARCHAR(50) COMMENT '所属区域',
  longitude DECIMAL(10,6) COMMENT '普通坐标经度',
  latitude DECIMAL(10,6) COMMENT '普通坐标纬度',
  cover_image VARCHAR(200) COMMENT '封面照片相对路径',
  manager_org VARCHAR(100) COMMENT '责任单位',
  manager_user_id BIGINT COMMENT '责任人',
  last_patrol_date DATE COMMENT '最近巡查日期',
  archive_status VARCHAR(20) NOT NULL DEFAULT '正常' COMMENT '正常/已迁移/已死亡/已销号',
  audit_status VARCHAR(20) NOT NULL DEFAULT '待审核' COMMENT '公开审核状态',
  version INT DEFAULT 1 COMMENT '版本号（乐观锁）',
  create_by VARCHAR(50),
  create_time DATETIME,
  update_time DATETIME,
  deleted TINYINT DEFAULT 0,
  UNIQUE KEY uk_tree_code (tree_code),
  KEY idx_tree_species (species),
  KEY idx_tree_level (protect_level),
  KEY idx_tree_region (region),
  KEY idx_tree_patrol (last_patrol_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='古树名木主档';
CREATE TABLE tree_version (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tree_id BIGINT NOT NULL,
  version_no INT NOT NULL COMMENT '版本序号',
  change_type VARCHAR(30) NOT NULL COMMENT '变更类型',
  before_json VARCHAR(1000) COMMENT '变更前快照',
  after_json VARCHAR(1000) COMMENT '变更后快照',
  reason VARCHAR(500) NOT NULL COMMENT '申请原因',
  applicant_id BIGINT,
  applicant_name VARCHAR(50),
  apply_time DATETIME,
  auditor_id BIGINT,
  auditor_name VARCHAR(50),
  audit_time DATETIME,
  audit_status VARCHAR(20) NOT NULL DEFAULT '待审核',
  audit_remark VARCHAR(300),
  KEY idx_version_tree (tree_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='树木变更版本';
CREATE TABLE tree_image (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tree_id BIGINT NOT NULL,
  category VARCHAR(20) NOT NULL COMMENT '全景/树干/树冠/病害/养护前/养护后',
  url VARCHAR(200) NOT NULL COMMENT '相对路径',
  original_name VARCHAR(200),
  file_size BIGINT,
  uploader_id BIGINT,
  create_time DATETIME,
  KEY idx_image_tree (tree_id, category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='古树影像';
CREATE TABLE patrol_plan (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  plan_code VARCHAR(50) NOT NULL,
  plan_name VARCHAR(100) NOT NULL,
  protect_level VARCHAR(20) COMMENT '适用保护等级',
  region VARCHAR(50),
  frequency INT COMMENT '每年巡查频次',
  assignee_id BIGINT,
  assignee_name VARCHAR(50),
  start_date DATE,
  end_date DATE,
  status VARCHAR(20) DEFAULT '草稿',
  remark VARCHAR(300),
  create_time DATETIME,
  UNIQUE KEY uk_plan_code (plan_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='巡查计划';
CREATE TABLE tree_patrol (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  patrol_code VARCHAR(50) NOT NULL,
  tree_id BIGINT NOT NULL,
  plan_id BIGINT,
  patrol_user_id BIGINT,
  patrol_user_name VARCHAR(50),
  patrol_time DATETIME,
  trunk_hollow VARCHAR(200) COMMENT '树干空洞',
  lean_degree VARCHAR(100) COMMENT '倾斜程度',
  dead_branch VARCHAR(100) COMMENT '枯枝',
  crown_deviation VARCHAR(100) COMMENT '树冠偏冠',
  pest_desc VARCHAR(200) COMMENT '病虫害',
  soil_desc VARCHAR(200) COMMENT '土壤生境',
  support_facility VARCHAR(100) COMMENT '支撑设施',
  lightning_facility VARCHAR(100) COMMENT '避雷设施',
  photos VARCHAR(500) COMMENT '现场照片',
  issue_level VARCHAR(20) COMMENT '问题分级',
  result VARCHAR(300) COMMENT '结论',
  status VARCHAR(20) DEFAULT '待提交',
  create_time DATETIME,
  UNIQUE KEY uk_patrol_code (patrol_code),
  KEY idx_patrol_tree (tree_id),
  KEY idx_patrol_time (patrol_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='巡查记录';
CREATE TABLE tree_issue (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  issue_code VARCHAR(50) NOT NULL,
  tree_id BIGINT NOT NULL,
  patrol_id BIGINT,
  issue_type VARCHAR(30) COMMENT '问题类型',
  severity VARCHAR(20) COMMENT '严重程度',
  issue_level VARCHAR(20) COMMENT '分级',
  description VARCHAR(500),
  status VARCHAR(20) DEFAULT '待处理',
  handle_order_id BIGINT,
  create_time DATETIME,
  UNIQUE KEY uk_issue_code (issue_code),
  KEY idx_issue_tree (tree_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='巡查问题';
CREATE TABLE care_order (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  order_code VARCHAR(50) NOT NULL,
  tree_id BIGINT NOT NULL,
  issue_id BIGINT,
  care_type VARCHAR(30) NOT NULL COMMENT '修剪/支撑/防腐/施肥/复壮/病虫害防治',
  plan_content VARCHAR(1000) COMMENT '方案内容',
  executor_org VARCHAR(100) COMMENT '养护单位',
  executor_user_id BIGINT,
  executor_name VARCHAR(50),
  plan_auditor_id BIGINT,
  plan_auditor_name VARCHAR(50),
  acceptor_id BIGINT,
  acceptor_name VARCHAR(50),
  status VARCHAR(20) NOT NULL DEFAULT '待方案' COMMENT '待方案/待审核/执行中/待验收/已完成',
  urgency VARCHAR(10) DEFAULT '普通',
  deadline DATE,
  progress INT DEFAULT 0,
  result_desc VARCHAR(500),
  reject_reason VARCHAR(300),
  temp_measure VARCHAR(300) COMMENT '紧急抢救临时措施',
  temp_measure_deadline DATETIME COMMENT '临时措施补全截止',
  create_time DATETIME,
  update_time DATETIME,
  UNIQUE KEY uk_order_code (order_code),
  KEY idx_order_tree (tree_id),
  KEY idx_order_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='养护工单';
CREATE TABLE care_drug (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  order_id BIGINT NOT NULL,
  drug_name VARCHAR(80) NOT NULL,
  dosage DECIMAL(10,2) NOT NULL COMMENT '本次剂量',
  unit VARCHAR(20) COMMENT '单位',
  apply_date DATE COMMENT '施用日期',
  operator_id BIGINT,
  operator_name VARCHAR(50),
  safety_measure VARCHAR(300) COMMENT '安全措施',
  plan_quota DECIMAL(10,2) COMMENT '方案核定总量',
  used_qty DECIMAL(10,2) COMMENT '累计用量',
  KEY idx_drug_order (order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用药记录';
CREATE TABLE annual_assessment (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tree_id BIGINT NOT NULL,
  assess_year INT NOT NULL,
  growth_score INT COMMENT '生长势',
  structure_score INT COMMENT '结构安全',
  pest_score INT COMMENT '病虫害',
  habitat_score INT COMMENT '生境',
  total_score INT COMMENT '综合得分',
  health_level VARCHAR(10) COMMENT '健康等级',
  suggestion VARCHAR(500) COMMENT '下年建议',
  assessor_id BIGINT,
  assessor_name VARCHAR(50),
  status VARCHAR(20) DEFAULT '已提交',
  create_time DATETIME,
  UNIQUE KEY uk_assess_tree_year (tree_id, assess_year)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='年度评估';
CREATE TABLE ancient_tree_rule (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  rule_name VARCHAR(100) NOT NULL,
  version INT NOT NULL COMMENT '版本号',
  weight_species INT NOT NULL COMMENT '树种权重',
  weight_age INT NOT NULL COMMENT '树龄权重',
  weight_level INT NOT NULL COMMENT '保护等级权重',
  weight_health INT NOT NULL COMMENT '健康等级权重',
  weight_season INT NOT NULL COMMENT '季节权重',
  weight_last_care INT NOT NULL COMMENT '上次养护时间权重',
  threshold_high INT DEFAULT 70 COMMENT '高分阈值',
  threshold_low INT DEFAULT 45 COMMENT '低分阈值',
  enabled TINYINT DEFAULT 1,
  effective_time DATETIME,
  create_time DATETIME
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='季节性养护计划规则';
CREATE TABLE ancient_tree_score (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tree_id BIGINT NOT NULL,
  rule_id BIGINT NOT NULL,
  rule_version INT NOT NULL,
  input_snapshot VARCHAR(1000) COMMENT '输入快照',
  detail_json VARCHAR(2000) COMMENT '明细分',
  total_score INT COMMENT '总分',
  result_level VARCHAR(20) COMMENT '优先养护/常规养护/暂缓',
  recommend_tasks VARCHAR(1000) COMMENT '推荐任务',
  explanation VARCHAR(1500) COMMENT '结果解释',
  unmet_json VARCHAR(500) COMMENT '未满足条件',
  manual_level VARCHAR(20) COMMENT '人工调整结果',
  manual_reason VARCHAR(500) COMMENT '调整原因',
  manual_by BIGINT,
  manual_time DATETIME,
  adopted TINYINT COMMENT '是否采纳',
  create_time DATETIME,
  KEY idx_score_tree (tree_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='养护计划计算留痕';

